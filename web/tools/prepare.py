"""Refresh the offline site's trace and measurement bundle from the RTL inputs."""
import csv
import json
from pathlib import Path

web = Path(__file__).resolve().parents[1]
root = web.parent
traces = {}
for path in sorted((root / 'verilog/traces').glob('*.txt')):
    traces[path.stem] = []
    for line in path.read_text().splitlines():
        operation, address, data = line.split()
        traces[path.stem].append({
            'write': operation == '1',
            'address': int(address, 16),
            'data': int(data, 16),
        })
csv_text = (root / 'results/comparison.csv').read_text()
results = list(csv.DictReader(csv_text.splitlines()))
bundle = {'traces': traces, 'results': results, 'csv': csv_text}
(web / 'data.js').write_text(
    '// Generated by web/tools/prepare.py.\nconst PROJECT_DATA = '
    + json.dumps(bundle, indent=2) + ';\n'
)
print(f'Updated web/data.js with {len(traces)} traces and {len(results)} RTL runs.')
